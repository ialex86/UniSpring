using System;
using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using System.Reflection;
using System.Text;

namespace UniSpring.DependencyInjection.Editor
{
    /// <summary>
    /// Writes the C# of the proxies IL2CPP needs (it cannot make proxy types at run time): one class per interface,
    /// implementing every member of it and of its base interfaces explicitly. Each call goes to the
    /// <see cref="IProxyHandler"/> with the interface method, the arguments and a delegate that calls the method on
    /// a target directly, so no reflection call is left for the player.
    /// </summary>
    internal static class ProxySourceWriter
    {
        /// <summary>The generated code is compiled into IL2CPP players only; the editor and Mono use run-time proxies.</summary>
        public const string PlayerGuard = "ENABLE_IL2CPP && !UNITY_EDITOR";

        public const string Header =
            "// <auto-generated>\n" +
            "// UniSpring IL2CPP proxies, written by the editor after every compilation.\n" +
            "// Do not edit; commit it with the code. Regenerate: Tools > UniSpring > Generate IL2CPP Proxies.\n" +
            "// </auto-generated>\n";

        /// <summary>
        /// The source for <paramref name="contracts"/>, which must all pass <see cref="WhyNot"/>. <paramref name="guard"/>
        /// wraps it in <c>#if</c>; null leaves it unguarded (tests).
        /// </summary>
        public static string Write(string assemblyName, IEnumerable<Type> contracts, string guard)
            => Write(assemblyName, contracts, Enumerable.Empty<Type>(), guard);

        /// <summary>
        /// As above, plus <paramref name="aotTypes"/>: generic types the container makes by reflection with value-type
        /// arguments (a strategy registry keyed by an enum), whose constructors IL2CPP must see used to compile them.
        /// </summary>
        public static string Write(string assemblyName, IEnumerable<Type> contracts, IEnumerable<Type> aotTypes, string guard)
        {
            var sorted = contracts.Distinct().OrderBy(TypeName, StringComparer.Ordinal).ToList();
            var space = "UniSpring.Generated." + Identifier(assemblyName);
            var text = new StringBuilder();
            text.Append(Header);
            if (guard != null)
                text.Append("#if ").Append(guard).Append('\n');
            text.Append("#pragma warning disable\n");
            for (var index = 0; index < sorted.Count; index++)
            {
                text.Append("[assembly: global::UniSpring.DependencyInjection.GeneratedProxy(typeof(")
                    .Append(TypeName(sorted[index])).Append("), typeof(global::").Append(space).Append(".Proxy")
                    .Append(index.ToString(CultureInfo.InvariantCulture)).Append("))]\n");
            }

            text.Append("\nnamespace ").Append(space).Append("\n{\n");
            for (var index = 0; index < sorted.Count; index++)
                WriteProxy(text, sorted[index], "Proxy" + index.ToString(CultureInfo.InvariantCulture));
            var hints = aotTypes.Distinct().OrderBy(TypeName, StringComparer.Ordinal).ToList();
            if (hints.Count > 0)
            {
                text.Append("    /// <summary>Never called: makes IL2CPP compile what the container creates by reflection.</summary>\n");
                text.Append("    [global::UnityEngine.Scripting.Preserve]\n    internal static class AotHints\n    {\n");
                text.Append("        [global::UnityEngine.Scripting.Preserve]\n        private static void Keep()\n        {\n");
                foreach (var hint in hints)
                    text.Append("            new ").Append(TypeName(hint)).Append("(null);\n");
                text.Append("        }\n    }\n");
            }

            text.Append("}\n");
            if (guard != null)
                text.Append("#endif\n");
            return text.ToString();
        }

        /// <summary>Why a proxy of <paramref name="contract"/> cannot be generated into <paramref name="assembly"/>, or null.</summary>
        public static string WhyNot(Type contract, Assembly assembly)
        {
            if (!contract.IsInterface)
                return "not an interface";
            if (contract.ContainsGenericParameters)
                return "an open generic interface";
            if (!IsVisible(contract, assembly))
                return "not visible from " + assembly.GetName().Name;
            foreach (var face in Faces(contract))
            {
                foreach (var method in face.GetMethods(BindingFlags.Instance | BindingFlags.Public | BindingFlags.DeclaredOnly))
                {
                    if (!method.IsAbstract)
                        continue; // a default implementation stays the interface's
                    var problem = WhyNot(method, assembly);
                    if (problem != null)
                        return face.Name + "." + method.Name + ": " + problem;
                }
            }

            return null;
        }

        private static string WhyNot(MethodInfo method, Assembly assembly)
        {
            if (method.ReturnType.IsByRef)
                return "returns by reference";
            foreach (var type in new[] { method.ReturnType }.Concat(method.GetParameters().Select(parameter => parameter.ParameterType)))
            {
                var plain = type.IsByRef ? type.GetElementType() : type;
                if (plain.IsPointer || IsByRefLike(plain))
                    return "uses " + plain.Name + ", which cannot be boxed";
                if (!IsVisible(plain, assembly))
                    return plain.Name + " is not visible from " + assembly.GetName().Name;
            }

            return null;
        }

        private static bool IsByRefLike(Type type)
        {
            var property = typeof(Type).GetProperty("IsByRefLike");
            return property != null && (bool)property.GetValue(type);
        }

        /// <summary>Whether code in <paramref name="assembly"/> can name <paramref name="type"/>.</summary>
        public static bool IsVisible(Type type, Assembly assembly)
        {
            if (type.IsGenericParameter)
                return true;
            if (type.IsArray || type.IsByRef || type.IsPointer)
                return IsVisible(type.GetElementType(), assembly);
            if (type.IsGenericType && !type.IsGenericTypeDefinition)
            {
                if (!type.GetGenericArguments().All(argument => IsVisible(argument, assembly)))
                    return false;
                type = type.GetGenericTypeDefinition();
            }

            var sameAssembly = type.Assembly == assembly;
            if (type.IsNested)
            {
                var nested = type.IsNestedPublic || (sameAssembly && (type.IsNestedAssembly || type.IsNestedFamORAssem));
                return nested && IsVisible(type.DeclaringType, assembly);
            }

            return type.IsPublic || sameAssembly;
        }

        private static IEnumerable<Type> Faces(Type contract)
            => new[] { contract }.Concat(contract.GetInterfaces().OrderBy(TypeName, StringComparer.Ordinal));

        // ---------------------------------------------------------------- one proxy

        private sealed class Member
        {
            public Type Face;
            public MethodInfo Method;
            public string Field;
        }

        private static void WriteProxy(StringBuilder text, Type contract, string name)
        {
            var members = new List<Member>();
            foreach (var face in Faces(contract))
            {
                foreach (var method in face.GetMethods(BindingFlags.Instance | BindingFlags.Public | BindingFlags.DeclaredOnly)
                             .Where(method => method.IsAbstract)
                             .OrderBy(method => method.Name, StringComparer.Ordinal)
                             .ThenBy(GeneratedProxies.Signature, StringComparer.Ordinal))
                {
                    members.Add(new Member { Face = face, Method = method, Field = "M" + members.Count.ToString(CultureInfo.InvariantCulture) });
                }
            }

            text.Append("    [global::UnityEngine.Scripting.Preserve]\n");
            text.Append("    internal sealed class ").Append(name).Append(" : global::UniSpring.DependencyInjection.GeneratedProxy, ")
                .Append(TypeName(contract)).Append("\n    {\n");
            foreach (var member in members)
            {
                text.Append("        private static readonly global::System.Reflection.MethodInfo ").Append(member.Field)
                    .Append(" = MethodOf(typeof(").Append(TypeName(member.Face)).Append("), ").Append(Literal(member.Method.Name))
                    .Append(", ").Append(Literal(GeneratedProxies.Signature(member.Method))).Append(");\n");
                if (!member.Method.IsGenericMethodDefinition)
                {
                    text.Append("        private static readonly global::System.Func<object, object[], object> D").Append(member.Field.Substring(1))
                        .Append(" = ").Append(Direct(member, "        ")).Append(";\n");
                }
            }

            text.Append("\n        [global::UnityEngine.Scripting.Preserve]\n");
            text.Append("        public ").Append(name).Append("(global::UniSpring.DependencyInjection.IProxyHandler handler) : base(handler)\n        {\n        }\n");

            var accessors = new HashSet<MethodInfo>();
            foreach (var face in Faces(contract))
            {
                foreach (var property in face.GetProperties().OrderBy(property => property.Name, StringComparer.Ordinal))
                    WriteProperty(text, property, members, accessors);
                foreach (var evt in face.GetEvents().OrderBy(evt => evt.Name, StringComparer.Ordinal))
                    WriteEvent(text, evt, members, accessors);
            }

            foreach (var member in members)
            {
                if (!accessors.Any(accessor => Same(accessor, member.Method)))
                    WriteMethod(text, member);
            }

            text.Append("    }\n\n");
        }

        private static Member Find(List<Member> members, MethodInfo method)
            => method == null ? null : members.FirstOrDefault(member => Same(member.Method, method));

        /// <summary>One method seen through two reflection calls (they may return different objects).</summary>
        private static bool Same(MethodInfo left, MethodInfo right)
            => left.MethodHandle == right.MethodHandle && left.DeclaringType == right.DeclaringType;

        private static void WriteMethod(StringBuilder text, Member member)
        {
            var method = member.Method;
            var parameters = method.GetParameters();
            text.Append("\n        ").Append(ReturnName(method.ReturnType)).Append(' ').Append(TypeName(member.Face)).Append('.')
                .Append(method.Name);
            if (method.IsGenericMethodDefinition)
                text.Append('<').Append(string.Join(", ", method.GetGenericArguments().Select(argument => argument.Name))).Append('>');
            text.Append('(').Append(string.Join(", ", parameters.Select((parameter, index) => Modifier(parameter) + TypeName(parameter.ParameterType) + " p" + index))).Append(")\n        {\n");
            WriteCallBody(text, member, parameters.Select((parameter, index) => "p" + index).ToArray(), parameters, method.ReturnType, "            ");
            text.Append("        }\n");
        }

        private static void WriteProperty(StringBuilder text, PropertyInfo property, List<Member> members, HashSet<MethodInfo> accessors)
        {
            var getter = Find(members, property.GetGetMethod());
            var setter = Find(members, property.GetSetMethod());
            if (getter == null && setter == null)
                return;
            var index = property.GetIndexParameters();
            text.Append("\n        ").Append(TypeName(property.PropertyType)).Append(' ').Append(TypeName(property.DeclaringType)).Append('.');
            if (index.Length == 0)
                text.Append(property.Name);
            else
                text.Append("this[").Append(string.Join(", ", index.Select((parameter, at) => TypeName(parameter.ParameterType) + " p" + at))).Append(']');
            text.Append("\n        {\n");
            var names = index.Select((parameter, at) => "p" + at).ToArray();
            if (getter != null)
            {
                accessors.Add(getter.Method);
                text.Append("            get\n            {\n");
                WriteCallBody(text, getter, names, getter.Method.GetParameters(), property.PropertyType, "                ");
                text.Append("            }\n");
            }

            if (setter != null)
            {
                accessors.Add(setter.Method);
                text.Append("            set\n            {\n");
                WriteCallBody(text, setter, names.Concat(new[] { "value" }).ToArray(), setter.Method.GetParameters(), typeof(void), "                ");
                text.Append("            }\n");
            }

            text.Append("        }\n");
        }

        private static void WriteEvent(StringBuilder text, EventInfo evt, List<Member> members, HashSet<MethodInfo> accessors)
        {
            var add = Find(members, evt.GetAddMethod());
            var remove = Find(members, evt.GetRemoveMethod());
            if (add == null || remove == null)
                return;
            accessors.Add(add.Method);
            accessors.Add(remove.Method);
            text.Append("\n        event ").Append(TypeName(evt.EventHandlerType)).Append(' ').Append(TypeName(evt.DeclaringType)).Append('.')
                .Append(evt.Name).Append("\n        {\n");
            text.Append("            add\n            {\n");
            WriteCallBody(text, add, new[] { "value" }, add.Method.GetParameters(), typeof(void), "                ");
            text.Append("            }\n            remove\n            {\n");
            WriteCallBody(text, remove, new[] { "value" }, remove.Method.GetParameters(), typeof(void), "                ");
            text.Append("            }\n        }\n");
        }

        /// <summary>Boxes the arguments, calls the handler, copies ref and out values back and returns the result.</summary>
        private static void WriteCallBody(
            StringBuilder text, Member member, string[] names, ParameterInfo[] parameters, Type returnType, string indent)
        {
            var method = member.Method;
            text.Append(indent).Append("var a = new object[] { ")
                .Append(string.Join(", ", parameters.Select((parameter, index) => parameter.IsOut && !parameter.IsIn
                    ? "default(" + TypeName(parameter.ParameterType.GetElementType()) + ")"
                    : names[index])))
                .Append(" };\n");
            string methodExpression;
            string direct;
            if (method.IsGenericMethodDefinition)
            {
                methodExpression = member.Field + ".MakeGenericMethod(" +
                                   string.Join(", ", method.GetGenericArguments().Select(argument => "typeof(" + argument.Name + ")")) + ")";
                direct = Direct(member, indent);
            }
            else
            {
                methodExpression = member.Field;
                direct = "D" + member.Field.Substring(1);
            }

            text.Append(indent).Append(returnType == typeof(void) ? "" : "var r = ").Append("Invoke(").Append(methodExpression)
                .Append(", a, ").Append(direct).Append(");\n");
            for (var index = 0; index < parameters.Length; index++)
            {
                if (!parameters[index].ParameterType.IsByRef || IsIn(parameters[index]))
                    continue;
                text.Append(indent).Append(names[index]).Append(" = ").Append(Unbox("a[" + index + "]", parameters[index].ParameterType.GetElementType()))
                    .Append(";\n");
            }

            if (returnType != typeof(void))
                text.Append(indent).Append("return ").Append(Unbox("r", returnType)).Append(";\n");
        }

        /// <summary>The delegate that calls the member on a target without reflection.</summary>
        private static string Direct(Member member, string indent)
        {
            var method = member.Method;
            var parameters = method.GetParameters();
            var body = new StringBuilder();
            body.Append("(target, args) =>\n").Append(indent).Append("{\n");
            var inner = indent + "    ";
            var arguments = new List<string>();
            for (var index = 0; index < parameters.Length; index++)
            {
                var parameter = parameters[index];
                if (!parameter.ParameterType.IsByRef)
                {
                    arguments.Add(Unbox("args[" + index + "]", parameter.ParameterType));
                    continue;
                }

                var element = parameter.ParameterType.GetElementType();
                body.Append(inner).Append(TypeName(element)).Append(" x").Append(index);
                if (!(parameter.IsOut && !parameter.IsIn))
                    body.Append(" = ").Append(Unbox("args[" + index + "]", element));
                body.Append(";\n");
                arguments.Add(Modifier(parameter) + "x" + index);
            }

            var target = "((" + TypeName(member.Face) + ")target)";
            string call;
            var property = AccessorOf(method);
            if (property != null && property.GetIndexParameters().Length == 0 && method.Name.StartsWith("get_", StringComparison.Ordinal))
                call = target + "." + property.Name;
            else if (property != null && method.Name.StartsWith("get_", StringComparison.Ordinal))
                call = target + "[" + string.Join(", ", arguments) + "]";
            else if (property != null && property.GetIndexParameters().Length == 0)
                call = target + "." + property.Name + " = " + arguments[0];
            else if (property != null)
                call = target + "[" + string.Join(", ", arguments.Take(arguments.Count - 1)) + "] = " + arguments[arguments.Count - 1];
            else if (EventOf(method) != null)
                call = target + "." + EventOf(method).Name + (method.Name.StartsWith("add_", StringComparison.Ordinal) ? " += " : " -= ") + arguments[0];
            else
            {
                call = target + "." + method.Name;
                if (method.IsGenericMethodDefinition)
                    call += "<" + string.Join(", ", method.GetGenericArguments().Select(argument => argument.Name)) + ">";
                call += "(" + string.Join(", ", arguments) + ")";
            }

            var returns = method.ReturnType != typeof(void);
            body.Append(inner).Append(returns ? "var result = " : "").Append(call).Append(";\n");
            for (var index = 0; index < parameters.Length; index++)
            {
                if (parameters[index].ParameterType.IsByRef && !IsIn(parameters[index]))
                    body.Append(inner).Append("args[").Append(index).Append("] = x").Append(index).Append(";\n");
            }

            body.Append(inner).Append(returns ? "return result;\n" : "return null;\n");
            body.Append(indent).Append('}');
            return body.ToString();
        }

        private static PropertyInfo AccessorOf(MethodInfo method)
        {
            if (!method.IsSpecialName)
                return null;
            return method.DeclaringType.GetProperties()
                .FirstOrDefault(property => Is(property.GetGetMethod(), method) || Is(property.GetSetMethod(), method));
        }

        private static EventInfo EventOf(MethodInfo method)
        {
            if (!method.IsSpecialName)
                return null;
            return method.DeclaringType.GetEvents()
                .FirstOrDefault(evt => Is(evt.GetAddMethod(), method) || Is(evt.GetRemoveMethod(), method));
        }

        private static bool Is(MethodInfo accessor, MethodInfo method) => accessor != null && Same(accessor, method);

        private static bool IsIn(ParameterInfo parameter) => parameter.ParameterType.IsByRef && parameter.IsIn && !parameter.IsOut;

        private static string Modifier(ParameterInfo parameter)
        {
            if (!parameter.ParameterType.IsByRef)
                return "";
            if (parameter.IsOut && !parameter.IsIn)
                return "out ";
            return IsIn(parameter) ? "in " : "ref ";
        }

        private static string Unbox(string value, Type type)
            => value + " == null ? default(" + TypeName(type) + ") : (" + TypeName(type) + ")" + value;

        // ---------------------------------------------------------------- names

        private static string ReturnName(Type type) => type == typeof(void) ? "void" : TypeName(type);

        /// <summary>The C# name of a type, fully qualified with <c>global::</c>.</summary>
        public static string TypeName(Type type)
        {
            if (type.IsByRef)
                return TypeName(type.GetElementType());
            if (type.IsGenericParameter)
                return type.Name;
            if (type.IsArray)
                return TypeName(type.GetElementType()) + "[" + new string(',', type.GetArrayRank() - 1) + "]";
            if (type == typeof(void))
                return "void";
            var arguments = type.IsGenericType ? type.GetGenericArguments() : Type.EmptyTypes;
            var chain = new List<Type>();
            for (var current = type; current != null; current = current.DeclaringType)
                chain.Insert(0, current.IsGenericType ? current.GetGenericTypeDefinition() : current);
            var text = new StringBuilder("global::");
            if (!string.IsNullOrEmpty(chain[0].Namespace))
                text.Append(chain[0].Namespace).Append('.');
            var used = 0;
            for (var index = 0; index < chain.Count; index++)
            {
                if (index > 0)
                    text.Append('.');
                var name = chain[index].Name;
                var tick = name.IndexOf('`');
                if (tick < 0)
                {
                    text.Append(name);
                    continue;
                }

                var arity = int.Parse(name.Substring(tick + 1), CultureInfo.InvariantCulture);
                text.Append(name, 0, tick).Append('<')
                    .Append(string.Join(", ", arguments.Skip(used).Take(arity).Select(TypeName))).Append('>');
                used += arity;
            }

            return text.ToString();
        }

        private static string Identifier(string name)
        {
            var text = new StringBuilder();
            foreach (var character in name)
                text.Append(char.IsLetterOrDigit(character) ? character : '_');
            if (text.Length == 0 || char.IsDigit(text[0]))
                text.Insert(0, '_');
            return text.ToString();
        }

        private static string Literal(string value) => "\"" + value.Replace("\\", "\\\\").Replace("\"", "\\\"") + "\"";
    }
